/**
 * Result representing the outcome of a Google Sign-In operation.
 */
sealed class GoogleAuthResult {
  data class Success(val user: AuthUser) : GoogleAuthResult()
  data class Error(val message: String, val cause: Throwable? = null) : GoogleAuthResult()
  object Cancelled : GoogleAuthResult()
}

/**
 * Dedicated Authentication Manager encapsulating Firebase Auth and Jetpack Credential Manager
 * to provide robust, modern Google Sign-In, silent auto-sign-in, and session lifecycle management.
 */
class UserAuthManager(
  private val context: Context,
  private val firebaseAuth: FirebaseAuth = try { Firebase.auth } catch (e: Throwable) { FirebaseAuth.getInstance() },
  private val credentialManager: CredentialManager = CredentialManager.create(context),
  private val repository: MeetMindRepository = MeetMindRepository.getInstance(),
  private val authRepository: AuthenticationRepository = FirebaseAuthRepository.getInstance()
) {

  private val _currentUser = MutableStateFlow<AuthUser?>(getCurrentMappedUser())
  val currentUser: StateFlow<AuthUser?> = _currentUser.asStateFlow()

  init {
    try {
      firebaseAuth.addAuthStateListener { auth ->
        val fbUser = auth.currentUser
        if (fbUser != null) {
          val authUser = mapFirebaseUserToAuthUser(fbUser)
          _currentUser.value = authUser
          syncUserWithRoster(authUser)
        } else {
          _currentUser.value = null
        }
      }
    } catch (e: Throwable) {
      Log.w(TAG, "Auth state listener setup skipped or unavailable: ${e.message}")
    }
  }

  /**
   * Retrieves the Web Client ID generated by Google Services plugin from google-services.json.
   */
  fun getWebClientId(): String {
    return context.getString(R.string.default_web_client_id)
  }

  /**
   * Interactively initiates Google Sign-In using Jetpack Credential Manager.
   *
   * In compliance with Android 16 (API 36) Credential Manager architecture:
   * - Uses [GetSignInWithGoogleOption] in a single-option [GetCredentialRequest].
   * - Distinctly catches [GetCredentialCancellationException] to avoid reporting user dismissal as an error.
   * - Authenticates with [FirebaseAuth] using [GoogleAuthProvider.getCredential].
   */
  suspend fun signInWithGoogle(activity: Activity): GoogleAuthResult = withContext(Dispatchers.IO) {
    val clientId = try {
      getWebClientId()
    } catch (e: Exception) {
      Log.e(TAG, "Web client ID resolution failed: ${e.message}", e)
      return@withContext GoogleAuthResult.Error(
        message = "Google Sign-In configuration missing: default_web_client_id not found.",
        cause = e
      )
    }

    val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
    val request = GetCredentialRequest.Builder()
      .addCredentialOption(signInOption)
      .build()

    try {
      val result = credentialManager.getCredential(activity, request)
      val credential = result.credential

      if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
        val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
        val authResult = firebaseAuth.signInWithCredential(authCredential).await()
        val fbUser = authResult.user

        if (fbUser != null) {
          val authUser = mapFirebaseUserToAuthUser(fbUser)
          _currentUser.value = authUser
          syncUserWithRoster(authUser)
          return@withContext GoogleAuthResult.Success(authUser)
        } else {
          return@withContext GoogleAuthResult.Error("Firebase user null after Google credential sign-in.")
        }
      } else {
        return@withContext GoogleAuthResult.Error("Unsupported credential type returned from Google Sign-In.")
      }
    } catch (e: GetCredentialCancellationException) {
      Log.w(TAG, "Google Sign-In flow cancelled or dismissed: ${e.message}", e)
      return@withContext GoogleAuthResult.Cancelled
    } catch (e: Exception) {
      Log.e(TAG, "Google Sign-In failed: ${e.message}", e)
      return@withContext GoogleAuthResult.Error(
        message = e.localizedMessage ?: "Google Sign-In failed. Please try again.",
        cause = e
      )
    }
  }

  /**
   * Attempts silent auto-sign-in on app startup for previously authorized Google accounts.
   * Uses [GetGoogleIdOption] with filterByAuthorizedAccounts = true in a dedicated request.
   */
  suspend fun attemptAutoSignIn(): GoogleAuthResult = withContext(Dispatchers.IO) {
    if (firebaseAuth.currentUser != null) {
      val authUser = mapFirebaseUserToAuthUser(firebaseAuth.currentUser!!)
      _currentUser.value = authUser
      return@withContext GoogleAuthResult.Success(authUser)
    }

    val clientId = try {
      getWebClientId()
    } catch (e: Exception) {
      return@withContext GoogleAuthResult.Error("Web client ID missing: ${e.message}")
    }

    val googleIdOption = GetGoogleIdOption.Builder()
      .setFilterByAuthorizedAccounts(true)
      .setServerClientId(clientId)
      .setAutoSelectEnabled(true)
      .build()

    val request = GetCredentialRequest.Builder()
      .addCredentialOption(googleIdOption)
      .build()

    try {
      val result = credentialManager.getCredential(context, request)
      val credential = result.credential

      if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
        val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
        val authResult = firebaseAuth.signInWithCredential(authCredential).await()
        val fbUser = authResult.user

        if (fbUser != null) {
          val authUser = mapFirebaseUserToAuthUser(fbUser)
          _currentUser.value = authUser
          syncUserWithRoster(authUser)
          return@withContext GoogleAuthResult.Success(authUser)
        }
      }
      return@withContext GoogleAuthResult.Cancelled
    } catch (e: Exception) {
      // Auto-sign-in absence is normal for first-time or logged-out users
      return@withContext GoogleAuthResult.Cancelled
    }
  }

  /**
   * Coroutine-scoped helper for UI triggers with callback handlers.
   */
  fun launchGoogleSignIn(
    activity: Activity,
    scope: CoroutineScope,
    onSuccess: (AuthUser) -> Unit,
    onError: (String) -> Unit,
    onCancelled: () -> Unit = {}
  ) {
    scope.launch {
      when (val result = signInWithGoogle(activity)) {
        is GoogleAuthResult.Success -> onSuccess(result.user)
        is GoogleAuthResult.Error -> onError(result.message)
        is GoogleAuthResult.Cancelled -> onCancelled()
      }
    }
  }

  /**
   * Signs the user out safely:
   * 1. Clears Credential Manager credential state inside [NonCancellable].
   * 2. Signs out from [FirebaseAuth].
   * 3. Resets user session state in repositories.
   */
  suspend fun signOut() = withContext(NonCancellable + Dispatchers.IO) {
    try {
      credentialManager.clearCredentialState(ClearCredentialStateRequest())
    } catch (e: Exception) {
      Log.w(TAG, "Failed to clear credential state: ${e.message}")
    } finally {
      try {
        firebaseAuth.signOut()
      } catch (e: Exception) {
        Log.w(TAG, "Failed to sign out from Firebase Auth: ${e.message}")
      }
      _currentUser.value = null
      authRepository.signOut()
    }
  }

  /**
   * Callback helper for sign-out triggers from Composables.
   */
  fun launchSignOut(scope: CoroutineScope, onComplete: () -> Unit = {}) {
    scope.launch {
      signOut()
      withContext(Dispatchers.Main) {
        onComplete()
      }
    }
  }

  private fun getCurrentMappedUser(): AuthUser? {
    val fbUser = try { firebaseAuth.currentUser } catch (e: Throwable) { null }
    return fbUser?.let { mapFirebaseUserToAuthUser(it) } ?: authRepository.currentUser.value
  }

  private fun mapFirebaseUserToAuthUser(fbUser: FirebaseUser): AuthUser {
    val email = fbUser.email ?: ""
    val matchingMember = repository.teamMembers.value.firstOrNull { it.email.equals(email, ignoreCase = true) }
    return AuthUser(
      uid = fbUser.uid,
      email = email,
      displayName = fbUser.displayName ?: matchingMember?.name ?: email.substringBefore("@").ifBlank { "Google User" },
      role = matchingMember?.role ?: UserRole.EMPLOYEE,
      department = matchingMember?.department ?: "Engineering",
      photoUrl = fbUser.photoUrl?.toString()
    )
  }

  private fun syncUserWithRoster(authUser: AuthUser) {
    val exists = repository.teamMembers.value.any { it.email.equals(authUser.email, ignoreCase = true) }
    if (!exists && authUser.email.isNotBlank()) {
      repository.addTeamMember(
        TeamMember(
          id = authUser.uid,
          name = authUser.displayName,
          email = authUser.email,
          department = authUser.department,
          role = authUser.role,
          avatarColorHex = 0xFF0066FF
        )
      )
    }
    repository.switchUser(authUser.uid)
  }

  companion object {
    private const val TAG = "UserAuthManager"

    @Volatile
    private var INSTANCE: UserAuthManager? = null

    fun getInstance(context: Context): UserAuthManager {
      return INSTANCE ?: synchronized(this) {
        INSTANCE ?: UserAuthManager(context.applicationContext).also { INSTANCE = it }
      }
    }
  }
}
